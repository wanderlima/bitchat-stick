def emit(name, width, height, data):
    lines = [f'// {name}: {width} x {height}, MSB first, row padded.', f'constexpr uint8_t {name}[] = {{']
    lines += ['  ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) + ',' for i in range(0, len(data), 16)]
    lines.append('};')
    return lines


