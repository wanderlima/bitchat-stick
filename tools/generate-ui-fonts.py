#!/usr/bin/env python3
"""Rasterize VT323 Regular into 1-bit GFX fonts for the Pocket UI.

FreeType's em is much taller than the visible capitals, so requesting a
2 px larger size only grows the ink by about 1 px. Each font is drawn once
at 80 px and nearest-neighbor scaled until 'H' is exactly `cap` pixels.
`cap` is 2 px above the previous on-device capital height. Cursor Y is the
top of that capital, matching LovyanGFX print() plus the preview baseline.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
font_path = root / 'src/assets/fonts/VT323-Regular.ttf'
# nominal yAdvance, capital height. Capitals are the previous ink + 2 px.
fonts = [
    (16, 10), (17, 10), (18, 12), (19, 12), (20, 12),
    (21, 13), (22, 13), (23, 15), (31, 19),
]
output = [
    '#pragma once',
    '// Generated by tools/generate-ui-fonts.py from VT323 Regular (OFL).',
    '// 1-bit ASCII 0x20-0x7E. See src/assets/fonts/OFL.txt.',
    'namespace stick { namespace assets {',
]
sample = 80
source = ImageFont.truetype(str(font_path), sample)
origin = sample


def source_glyph(char):
    canvas = Image.new('L', (sample * 3, sample * 3), 0)
    ImageDraw.Draw(canvas).text((origin, origin), char, font=source, fill=255, anchor='ls')
    return canvas.point(lambda pixel: 255 if pixel >= 96 else 0)


reference = source_glyph('H').getbbox()
reference_cap = reference[3] - reference[1]
mono = source.getlength('M')


def raster(nominal, cap):
    scale = cap / reference_cap
    advance = max(1, round(mono * scale))
    bitmap, glyphs = [], []
    for code in range(0x20, 0x7F):
        if code == 0x20:
            glyphs.append((0, 0, 0, advance, 0, 0, code))
            continue
        image = source_glyph(chr(code))
        bbox = image.getbbox()
        if not bbox:
            glyphs.append((0, 0, 0, advance, 0, 0, code))
            continue
        x0, y0, x1, y1 = bbox
        width = max(1, round((x1 - x0) * scale))
        height = max(1, round((y1 - y0) * scale))
        crop = image.crop(bbox).resize((width, height), Image.Resampling.NEAREST)
        values = [crop.getpixel((x, y)) >= 128 for y in range(height) for x in range(width)]
        glyphs.append((
            len(bitmap), width, height, advance,
            round((x0 - origin) * scale), round((y0 - origin) * scale), code,
        ))
        for index in range(0, len(values), 8):
            bitmap.append(sum((0x80 >> bit) for bit, on in enumerate(values[index:index + 8]) if on))
    return bitmap, glyphs, advance


checks = {}
for nominal, cap in fonts:
    bitmap, glyphs, advance = raster(nominal, cap)
    name = f'Vt323{nominal}'
    output.append(f'const uint8_t {name}Bitmaps[] = {{')
    output += ['  ' + ', '.join(f'0x{x:02x}' for x in bitmap[i:i + 16]) + ',' for i in range(0, max(len(bitmap), 1), 16)]
    if not bitmap:
        output.append('  0x00,')
    output.append('};')
    output.append(f'const lgfx::GFXglyph {name}Glyphs[] = {{')
    output += ['  {' + ', '.join(map(str, glyph[:6])) + '}, // 0x%02X' % glyph[6] for glyph in glyphs]
    output += ['};', f'const lgfx::GFXfont {name} = {{(uint8_t*){name}Bitmaps, (lgfx::GFXglyph*){name}Glyphs, 0x20, 0x7e, {nominal}}};']
    checks[nominal] = advance
    cap_glyph = next(glyph for glyph in glyphs if glyph[6] == ord('H'))
    print(f'{nominal}px cap {cap_glyph[2]} advance {advance}')

output += ['} } // namespace stick::assets', '']
(root / 'src/assets/UiFonts.h').write_text('\n'.join(output) + '\n')
for nominal, text in ((31, 'Bitchat Stick'), (23, 'Short messages'), (16, 'Hold B Back'), (16, 'B/C Change')):
    print(f'{text!r} at {nominal}px = {checks[nominal] * len(text)}px')
