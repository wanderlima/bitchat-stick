#!/usr/bin/env python3
"""Build native 14/16px FreeMono bitmaps from pinned M5GFX glyphs.

Area sampling retains thin strokes when reducing the existing 18px bitmaps.
Output uses integer advances and is rendered at 1x on the device.
"""
from pathlib import Path
import re
import math
root = Path(__file__).resolve().parents[1]
source = root / '.pio/libdeps/m5stickc-plus2/M5GFX/src/lgfx/Fonts/GFXFF'
output = ['#pragma once', '// Generated by tools/generate-ui-fonts.py from M5GFX 0.3.0 FreeMono glyphs.',
          '// Retains the upstream FreeMono artwork; native integer pixel sizes, no runtime scaling.',
          'namespace stick { namespace assets {']
for name, original, height in [('FreeMonoCompact14', 'FreeMono9pt7b', 14), ('FreeMonoBody16', 'FreeMonoBold9pt7b', 16)]:
    text = (source / (original + '.h')).read_text()
    data = bytes(int(x, 16) for x in re.findall(r'0x([0-9A-Fa-f]{2})', text.split('Bitmaps[] PROGMEM = {')[1].split('};')[0]))
    glyphs = [(int(g[6], 16), *map(int, g[:6])) for g in re.findall(r'\{\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(-?\d+),\s*(-?\d+)\s*\}[^\n]*// 0x([0-9A-Fa-f]+)', text)]
    scale = height / 18
    bitmap, converted = [], []
    for code, offset, w, h, advance, xo, yo in glyphs:
        left, top = math.floor(xo * scale), math.floor(yo * scale)
        right, bottom = math.ceil((xo + w) * scale), math.ceil((yo + h) * scale)
        nw, nh = right - left, bottom - top
        values = []
        for y in range(nh):
            for x in range(nw):
                coverage = 0
                for sy in range(h):
                    dy = max(0, min(top + y + 1, (yo + sy + 1) * scale) - max(top + y, (yo + sy) * scale))
                    if not dy:
                        continue
                    for sx in range(w):
                        dx = max(0, min(left + x + 1, (xo + sx + 1) * scale) - max(left + x, (xo + sx) * scale))
                        bit = sy * w + sx
                        if data[offset + bit // 8] & (0x80 >> (bit % 8)):
                            coverage += dx * dy
                values.append(coverage >= .22)
        converted.append((len(bitmap), nw, nh, round(advance * scale), left, top, code))
        for i in range(0, len(values), 8):
            bitmap.append(sum((0x80 >> j) for j, on in enumerate(values[i:i+8]) if on))
    output.append(f'const uint8_t {name}Bitmaps[] = {{')
    output += ['  ' + ', '.join(f'0x{x:02x}' for x in bitmap[i:i+16]) + ',' for i in range(0, len(bitmap), 16)]
    output.append('};')
    output.append(f'const lgfx::GFXglyph {name}Glyphs[] = {{')
    output += ['  {' + ', '.join(map(str, g[:6])) + '}, // 0x%02X' % g[6] for g in converted]
    output += ['};', f'const lgfx::GFXfont {name} = {{(uint8_t*){name}Bitmaps, (lgfx::GFXglyph*){name}Glyphs, 0x20, 0x7e, {height}}};']
output += ['} } // namespace stick::assets', '']
(root / 'src/assets/UiFonts.h').write_text('\n'.join(output))
